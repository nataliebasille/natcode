#!/usr/bin/env python3
"""Generate docs/natcode-spec.md by merging the files in docs/spec/."""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

DOCS = Path(__file__).resolve().parents[1]
OUTPUT = DOCS / 'natcode-spec.md'
SECTIONS = ['lexical', 'syntax-and-types', 'variables', 'modules', 'evaluation']

HEADER = """# Natcode — consolidated language specification

> Generated by `docs/tools/build_spec.py` from the files in `spec/`. Edit those files, not this one.

This document merges the Natcode language specification into a single file. Decision and implementation status for every item, including open questions, is tracked in the [scorecards](scorecards/README.md), not here.
"""

LINK = re.compile(r'\]\((?!https?://|#)([^)]+)\)')


def rewrite_link(match: re.Match) -> str:
    target = match.group(1)
    if target.startswith('../'):
        return f']({target[3:]})'
    return f'](spec/{target})'


def build() -> str:
    parts = [HEADER.rstrip('\n')]
    for name in SECTIONS:
        text = (DOCS / 'spec' / f'{name}.md').read_text(encoding='utf-8').strip('\n')
        parts.append(LINK.sub(rewrite_link, text))
    return '\n\n---\n\n'.join(parts) + '\n'


def main() -> int:
    cli = argparse.ArgumentParser(description=__doc__)
    cli.add_argument('--check', action='store_true', help='Fail if natcode-spec.md is out of date instead of writing it')
    args = cli.parse_args()
    content = build()
    if args.check:
        current = OUTPUT.read_text(encoding='utf-8') if OUTPUT.exists() else ''
        if current != content:
            print('natcode-spec.md is out of date; run python docs/tools/build_spec.py', file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(content, encoding='utf-8', newline='\n')
    return 0


if __name__ == '__main__':
    sys.exit(main())
